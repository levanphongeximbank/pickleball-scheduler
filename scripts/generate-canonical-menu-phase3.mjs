/**
 * Phase 3 — sync canonical menu metadata from Phase 1 inventory.
 * - Marks PARTIAL badges (CRM + /reports)
 * - Hides parameterized routes from general menu surfaces (contextual only)
 * - Emits route classification catalog for all inventoried routes
 *
 * Does not invent new menu authority beyond inventory proposedCanonicalMenu.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const inventoryPath = path.join(root, "docs/ui-ux/canonical-navigation/CANONICAL_ROUTE_INVENTORY.json");
const menuDataPath = path.join(root, "src/features/canonical-shell/config/canonicalMenuData.js");
const catalogPath = path.join(root, "src/features/canonical-shell/config/canonicalRouteCatalog.js");

const PARTIAL_ROUTES = new Set([
  "/reports",
  "/crm/messages",
  "/crm/templates",
  "/crm/campaigns",
  "/crm/history",
  "/crm/reminders/booking",
]);

const inventory = JSON.parse(fs.readFileSync(inventoryPath, "utf8"));
const routes = inventory.routes || [];

const catalogEntries = routes.map((route) => ({
  path: route.path,
  classification: route.classification,
  disposition: route.disposition,
  proposedCanonicalMenu: Boolean(route.proposedCanonicalMenu),
  level1: route.level1 || null,
  level2: route.level2 || null,
  level3: route.level3 || null,
  ownerDecision: route.ownerDecision || null,
  sidebar: Boolean(route.sidebar),
  mobile: Boolean(route.mobile),
}));

const classificationCounts = catalogEntries.reduce((acc, entry) => {
  acc[entry.classification] = (acc[entry.classification] || 0) + 1;
  return acc;
}, {});

const catalogSource = `/** Auto-generated by scripts/generate-canonical-menu-phase3.mjs — do not hand-edit. */
export const CANONICAL_ROUTE_CATALOG = Object.freeze({
  meta: Object.freeze(${JSON.stringify(
    {
      source: "docs/ui-ux/canonical-navigation/CANONICAL_ROUTE_INVENTORY.json",
      generatedAt: new Date().toISOString(),
      phase: "3-menu-completion",
      totalRoutes: catalogEntries.length,
      proposedCanonicalMenuCount: catalogEntries.filter((e) => e.proposedCanonicalMenu).length,
      classificationCounts,
    },
    null,
    2
  )}),
  routes: Object.freeze(
    ${JSON.stringify(catalogEntries, null, 2)}.map((entry) => Object.freeze(entry))
  ),
});

export function listCanonicalRouteCatalog() {
  return CANONICAL_ROUTE_CATALOG.routes;
}

export function getRouteCatalogEntry(pathname) {
  const target = String(pathname || "");
  return CANONICAL_ROUTE_CATALOG.routes.find((entry) => entry.path === target) || null;
}

export function countRoutesByClassification(classification) {
  return CANONICAL_ROUTE_CATALOG.routes.filter((entry) => entry.classification === classification).length;
}
`;

fs.writeFileSync(catalogPath, catalogSource);

// Patch menu data file in place (preserve hand-authored labels/icons).
let menuSrc = fs.readFileSync(menuDataPath, "utf8");

menuSrc = menuSrc.replace(
  /"phase": "2-foundation"/,
  '"phase": "3-menu-completion"'
);
menuSrc = menuSrc.replace(
  /"generatedAt": "[^"]+"/,
  `"generatedAt": "${new Date().toISOString()}"`
);

for (const route of PARTIAL_ROUTES) {
  const routeLiteral = JSON.stringify(route);
  const routeIdx = menuSrc.indexOf(`"route": ${routeLiteral}`);
  if (routeIdx < 0) {
    console.warn("PARTIAL route missing from menu data:", route);
    continue;
  }
  // Replace nearest visibilityStatus / badge within this node object window.
  const windowStart = menuSrc.lastIndexOf("{", routeIdx);
  const windowEnd = menuSrc.indexOf("\n    },", routeIdx);
  if (windowStart < 0 || windowEnd < 0) continue;
  let chunk = menuSrc.slice(windowStart, windowEnd);
  chunk = chunk.replace(/"visibilityStatus": "live"/, '"visibilityStatus": "partial"');
  chunk = chunk.replace(/"badge": null/, '"badge": {\n        "label": "Một phần",\n        "tone": "partial"\n      }');
  chunk = chunk.replace(/"badge": \{\s*"label": "PARTIAL"/, '"badge": {\n        "label": "Một phần"');
  menuSrc = menuSrc.slice(0, windowStart) + chunk + menuSrc.slice(windowEnd);
}

// Parameterized tournament family — contextual only (not general menu / search).
for (const route of routes.filter((r) => r.proposedCanonicalMenu && String(r.path || "").includes(":"))) {
  const routeLiteral = JSON.stringify(route.path);
  const routeIdx = menuSrc.indexOf(`"route": ${routeLiteral}`);
  if (routeIdx < 0) continue;
  const windowStart = menuSrc.lastIndexOf("{", routeIdx);
  const windowEnd = menuSrc.indexOf("\n    },", routeIdx);
  if (windowStart < 0 || windowEnd < 0) continue;
  let chunk = menuSrc.slice(windowStart, windowEnd);
  chunk = chunk.replace(/"desktopVisible": true/, '"desktopVisible": false');
  chunk = chunk.replace(/"mobileVisible": true/, '"mobileVisible": false');
  if (!chunk.includes('"contextualOnly"')) {
    chunk = chunk.replace(
      /"proposedCanonicalMenu": true/,
      '"proposedCanonicalMenu": true,\n      "contextualOnly": true'
    );
  }
  menuSrc = menuSrc.slice(0, windowStart) + chunk + menuSrc.slice(windowEnd);
}

fs.writeFileSync(menuDataPath, menuSrc);

console.log("Wrote", path.relative(root, catalogPath));
console.log("Patched", path.relative(root, menuDataPath));
console.log("Catalog routes:", catalogEntries.length);
console.log("PARTIAL routes:", [...PARTIAL_ROUTES].join(", "));
