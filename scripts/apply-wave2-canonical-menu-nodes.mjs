function toMenuNode(spec) {
  const inv = inventory.routes.find((r) => r.path === spec.route);
  if (!inv || !inv.proposedCanonicalMenu) {
    throw new Error(`Inventory missing proposedCanonicalMenu for ${spec.route}`);
  }
  return {
    id: spec.id,
    label: spec.label,
    description: spec.description,
    icon: spec.icon,
    route: spec.route,
    level1: spec.level1,
    level1Label: spec.level1Label,
    level2: spec.level2,
    level2Label: spec.level2Label,
    level3: spec.level3,
    children: [],
    requiredRoles: [],
    requiredPermissions: [...spec.requiredPermissions],
    featureFlags: [...spec.featureFlags],
    visibilityStatus: "live",
    activeMatch: "prefix",
    mobileVisible: true,
    desktopVisible: true,
    badge: null,
    proposedCanonicalMenu: true,
    classification: "CANONICAL",
    rbacVisibility: [...spec.rbacVisibility],
    sidebar: spec.sidebar,
    guards: [...spec.guards],
  };
}

